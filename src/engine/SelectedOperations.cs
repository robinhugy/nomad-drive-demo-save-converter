using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace NomadSave
{
    internal static class SelectedOperations
    {
        internal static int CurrentLimit(Manifest m)
        {
            if (m.Format == 16) return Math.Max(1, Math.Min(8, (int)(m.Economy >> 56)));
            string host = m.Host == null ? "" : m.Host.Puid;
            return Math.Max(1, 1 + m.Remote.Where(p => p.Puid.Length > 0 && p.Puid != host).Select(p => p.Puid).Distinct().Count());
        }
        internal static Conversion SetLimit(byte[] data, Mapping mapping, int players)
        {
            if (players < 1 || players > 8) throw new ConversionError("Player limit must be an integer from 1 to 8.");
            var save = SaveFormat.Decode(data); byte[] before = save.Entries["game.manifest"]; var m = SaveFormat.Parse(before);
            if (m.Format != 16) throw new ConversionError("The selected operation requires a current save.");
            int previous = CurrentLimit(m); m.Economy = ConverterCore.WithPlayers(m.Economy, players);
            byte[] after = SaveFormat.Serialize(m);
            if (before.Length != after.Length || !before.Take(before.Length - 1).SequenceEqual(after.Take(after.Length - 1))) throw new ConversionError("Unexpected data changed outside the player limit.");
            save.Entries["game.manifest"] = after; byte[] output = before.SequenceEqual(after) ? data : SaveFormat.Encode(save); SaveFormat.Verify(output, save);
            var report = ConverterCore.BaseReport(data, m, mapping); ConverterCore.CompleteReport(report, m, output);
            report["operation"] = "set-player-limit"; report["previousPlayerSlots"] = previous; report["playerSlots"] = players; report["multiplayerEnabled"] = players > 1;
            report["verification"] = "Only the player-limit byte may change. All other manifest bytes, player records and sidecars are preserved; container CRC and exact read-back verified.";
            Json.List(report, "warnings").Add("All saved player profiles and inventories are retained when lowering the simultaneous player limit. A limit of 1 makes the copy single-player.");
            return new Conversion { Output = output, Report = report };
        }
        internal static Conversion Prepare(byte[] data, Mapping mapping, string action, int? requested, bool replace)
        {
            if (action != "migrate" && action != "multiplayer" && action != "players") throw new ConversionError("Unknown selected action: " + action);
            if (action == "players" && !requested.HasValue) throw new ConversionError("Choose a player limit for this world.");
            if (requested.HasValue && (requested.Value < 1 || requested.Value > 8)) throw new ConversionError("Player limit must be an integer from 1 to 8.");
            var save = SaveFormat.Decode(data); var m = SaveFormat.Parse(save.Entries["game.manifest"]);
            if (m.Format != 5 && m.Format != 16) throw new ConversionError("Unsupported save format. The source is unchanged.");
            int current = CurrentLimit(m), desired = action == "players" ? requested.Value : action == "multiplayer" ? Math.Max(2, current) : current;
            Conversion conversion;
            if (m.Format == 5)
            {
                // First retain every historical player; the explicit cap operation can then lower concurrency safely.
                conversion = ConverterCore.Transform(data, mapping, replace, current);
                if (desired != current) { var limit = SetLimit(conversion.Output, mapping, desired); conversion.Output = limit.Output; Json.List(conversion.Report, "warnings").AddRange(Json.List(limit.Report, "warnings")); }
            }
            else
            {
                var unknown = m.Objects.Where(o => !mapping.Assets.ContainsKey(o.Asset)).Select(o => o.Asset).Distinct().ToArray();
                if (unknown.Length > 0) throw new ConversionError("This current-format world contains assets absent from the target game: " + string.Join(", ", unknown) + ". An updated mapping is required; nothing was removed.");
                conversion = SetLimit(data, mapping, desired);
                Json.List(conversion.Report, "warnings").Add("Current-format demo progress, world objects, paint, inventory and shared state are copied intact. Terrain and buildings are generated by the target game.");
            }
            var report = conversion.Report; report["operation"] = action; report["targetEdition"] = "Early Access"; report["previousPlayerSlots"] = current;
            report["sourceSha256"] = SaveFormat.Sha(data); report["sourceFormat"] = m.Format; report["playerSlots"] = desired; report["multiplayerEnabled"] = desired > 1;
            ConverterCore.CompleteReport(report, SaveFormat.Parse(SaveFormat.Decode(conversion.Output).Entries["game.manifest"]), conversion.Output);
            return conversion;
        }
        sealed class Job
        {
            internal string Source, Name; internal Conversion Conversion;
        }
        internal static Dictionary<string, object> Execute(Dictionary<string, object> plan, bool apply, Mapping targetMapping = null)
        {
            var mapping = targetMapping ?? Mapping.LoadEarlyAccess(); string game = Json.S(plan, "game"); SaveOperations.VerifyBuild(game, mapping);
            string output = SaveOperations.CanonicalPath(Json.S(plan, "outputRoot", SaveOperations.DefaultEarlyAccessSaves));
            string backups = SaveOperations.CanonicalPath(Json.S(plan, "backupRoot", SaveOperations.DefaultBackups));
            var requests = Json.Items(Json.Get(plan, "selections")).Select(Json.Dict).ToList();
            if (requests.Count == 0) throw new ConversionError("Select at least one world.");
            if (requests.Count > 500) throw new ConversionError("Select no more than 500 worlds at once.");
            if (apply && SaveOperations.GameRunning()) throw new ConversionError("Close the game before creating converted copies.");
            var jobs = new List<Job>(); var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            bool replace = Convert.ToBoolean(Json.Get(plan, "replaceMissing", true)), cleanup = Convert.ToBoolean(Json.Get(plan, "cleanLegacyLoot", false));
            foreach (var request in requests)
            {
                string source = SaveOperations.SourceFile(Json.S(request, "source")); string slot = Path.GetDirectoryName(source);
                if (!seen.Add(slot)) throw new ConversionError("The same source world was selected more than once.");
                SaveOperations.ValidateDestinations(slot, output, backups);
                byte[] data = SaveOperations.ReadSave(source); string expected = Json.S(request, "expectedSha256");
                if (expected.Length == 0 || expected != SaveFormat.Sha(data)) throw new ConversionError("A selected save changed, or has no preview fingerprint. Refresh the list and preview again.");
                object value = Json.Get(request, "players"); int? players = null;
                if (value != null) { if (!(value is int)) throw new ConversionError("Player limit must be an integer from 1 to 8."); players = (int)value; }
                var conversion = Prepare(data, mapping, Json.S(request, "action", "migrate"), players, replace);
                if (cleanup) conversion = LootCleanup.Apply(source, conversion, mapping, backups, Json.Get(request, "legacySource") as string);
                string name = SaveOperations.ConvertedName(Json.S(SaveOperations.ReadMeta(slot), "displayName", Path.GetFileName(slot)));
                conversion.Report["displayName"] = name;
                jobs.Add(new Job { Source = slot, Name = name, Conversion = conversion });
            }
            // All selected worlds and write boundaries pass preflight before any destination or backup is created.
            if (apply) { if (SaveOperations.GameRunning()) throw new ConversionError("Close the game before creating converted copies."); Directory.CreateDirectory(output); }
            var results = new List<object>(); var errors = new List<object>();
            foreach (var job in jobs)
            {
                try
                {
                    var report = apply ? SaveOperations.ConvertSlot(job.Source, output, backups, mapping, game, replace, job.Name, null, true, false, null, job.Conversion) : job.Conversion.Report;
                    results.Add(report);
                }
                catch (Exception ex) { errors.Add(Json.D("name", job.Name, "error", ex.Message)); }
            }
            var text = new List<string> { (apply ? "Created copies: " : "Previewed worlds: ") + results.Count + "; errors: " + errors.Count, "Destination: " + output, "Only the selected worlds are processed. Original saves are unchanged.", "" };
            foreach (var report in results.Select(Json.Dict)) text.Add(ConverterCore.ReportText(report));
            foreach (var error in errors.Select(Json.Dict)) text.Add(Json.S(error, "name") + ": " + error["error"]);
            return Json.D("applied", apply, "selected", jobs.Count, "created", apply ? results.Count : 0, "worlds", results, "errors", errors, "reportText", string.Join("\n", text));
        }
        internal static List<Dictionary<string, object>> ListWorlds(IEnumerable<string> roots)
        {
            var rows = new List<Dictionary<string, object>>(); var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (string root in roots.Where(r => !string.IsNullOrWhiteSpace(r)))
            {
                if (!Directory.Exists(root)) continue;
                foreach (string folder in Directory.GetDirectories(root, "slot_*"))
                {
                    if (!seen.Add(SaveOperations.CanonicalPath(folder))) continue;
                    if (!File.Exists(Path.Combine(folder, "save.dat")) && !File.Exists(Path.Combine(folder, "autosave.dat"))) continue;
                    try
                    {
                        var row = SaveOperations.Inspect(folder); var manifest = SaveFormat.Parse(SaveFormat.Decode(SaveOperations.ReadSave(Json.S(row, "path"))).Entries["game.manifest"]);
                        row["players"] = CurrentLimit(manifest); row["profile"] = root.IndexOf("Nomad Drive Demo", StringComparison.OrdinalIgnoreCase) >= 0 ? "Demo" : root.IndexOf("Nomad Drive", StringComparison.OrdinalIgnoreCase) >= 0 ? "Early Access" : "Custom"; rows.Add(row);
                    }
                    catch (Exception ex) { rows.Add(Json.D("slot", folder, "name", Path.GetFileName(folder), "error", ex.Message, "modified", 0, "players", "?", "profile", "Unreadable")); }
                }
            }
            return rows.OrderByDescending(r => Convert.ToDouble(r["modified"])).ToList();
        }
    }
}
